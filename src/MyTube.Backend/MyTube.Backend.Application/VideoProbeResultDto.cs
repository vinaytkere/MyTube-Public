using System.Collections.Generic;

namespace MyTube.Backend.Application;

public class MediaTrackInfoDto
{
    public string Code { get; set; } = string.Empty;
    public string Name { get; set; } = string.Empty;
    public bool IsOriginal { get; set; }
    public bool IsAutoGenerated { get; set; }
}

public class VideoProbeResultDto
{
    public string Title { get; set; } = string.Empty;
    public double? DurationSeconds { get; set; }
    public string FormattedDuration { get; set; } = string.Empty;
    public string? ThumbnailUrl { get; set; }
    public string? Description { get; set; }
    public string? Uploader { get; set; }
    public List<string> Tags { get; set; } = new();
    public List<string> Qualities { get; set; } = new();
    public bool SubtitlesAvailable { get; set; }
    public List<string> SubtitleLanguages { get; set; } = new();
    public List<MediaTrackInfoDto> SubtitleTracks { get; set; } = new();
    public List<string> AudioLanguages { get; set; } = new();
    public List<MediaTrackInfoDto> AudioTracks { get; set; } = new();
}
