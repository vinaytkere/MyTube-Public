using System;
using System.IO;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using MyTube.Backend.Application;
using MyTube.Backend.Domain;
using MyTube.Backend.Infrastructure;
using Xunit;

namespace MyTube.Backend.Tests;

public class VideoSubtitleTests : IDisposable
{
    private readonly string _tempDir;

    public VideoSubtitleTests()
    {
        _tempDir = Path.Combine(Path.GetTempPath(), $"mytube_subs_{Guid.NewGuid():N}");
        Directory.CreateDirectory(_tempDir);
    }

    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_tempDir))
            {
                Directory.Delete(_tempDir, true);
            }
        }
        catch { }
    }

    [Fact]
    public async Task GetVideoById_DiscoversSidecarVttAndSrtSubtitles()
    {
        var options = new DbContextOptionsBuilder<VideoDbContext>()
            .UseInMemoryDatabase(databaseName: Guid.NewGuid().ToString())
            .Options;

        var videoFile = Path.Combine(_tempDir, "sample_clip.mp4");
        var vttSub = Path.Combine(_tempDir, "sample_clip.en.vtt");
        var srtSub = Path.Combine(_tempDir, "sample_clip.es.srt");

        File.WriteAllText(videoFile, "dummy video");
        File.WriteAllText(vttSub, "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nHello World\n");
        File.WriteAllText(srtSub, "1\n00:00:01,000 --> 00:00:03,000\nHola Mundo\n");

        using var db = new VideoDbContext(options);
        var category = new Category { Id = 1, Name = "Tests" };
        db.Categories.Add(category);

        var video = new Video
        {
            Id = Guid.NewGuid(),
            FilePath = videoFile,
            FileName = "sample_clip.mp4",
            DisplayTitle = "Sample Clip",
            CategoryId = category.Id,
            ScanStatus = ScanState.Ready,
            CreatedAt = DateTime.UtcNow
        };
        db.Videos.Add(video);
        await db.SaveChangesAsync();

        var config = new ConfigurationBuilder().Build();
        var videoService = new VideoService(db, config);

        var result = await videoService.GetVideoByIdAsync(video.Id, "vinay", "http://localhost:5000");

        Assert.NotNull(result);
        Assert.Equal(2, result.SubtitleTracks.Count);

        var enTrack = result.SubtitleTracks.Find(t => t.Language == "en");
        Assert.NotNull(enTrack);
        Assert.Equal("English", enTrack.Label);
        Assert.Contains($"/api/videos/{video.Id}/subtitles/", enTrack.Src);

        var esTrack = result.SubtitleTracks.Find(t => t.Language == "es");
        Assert.NotNull(esTrack);
        Assert.Equal("Spanish", esTrack.Label);
    }

