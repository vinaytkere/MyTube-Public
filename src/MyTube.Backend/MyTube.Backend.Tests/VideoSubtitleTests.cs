    [Fact]
    public async Task GetVideoById_PrioritizesCleanSubtitlesOverAutoGenerated()
    {
        var options = new DbContextOptionsBuilder<VideoDbContext>()
            .UseInMemoryDatabase(databaseName: Guid.NewGuid().ToString())
            .Options;

        var videoFile = Path.Combine(_tempDir, "vedanta_clip.mp4");
        var manualVtt = Path.Combine(_tempDir, "vedanta_clip.en.vtt");
        var autoVtt = Path.Combine(_tempDir, "vedanta_clip.en-orig.vtt");

        File.WriteAllText(videoFile, "dummy video");
        File.WriteAllText(manualVtt, "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nVedanta teaches you\n");
        File.WriteAllText(autoVtt, "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nFedanta teaches you\n");

        using var db = new VideoDbContext(options);
        var category = new Category { Id = 1, Name = "Philosophy" };
        db.Categories.Add(category);

        var video = new Video
        {
            Id = Guid.NewGuid(),
            FilePath = videoFile,
            FileName = "vedanta_clip.mp4",
            DisplayTitle = "Vedanta Clip",
            CategoryId = category.Id,
            ScanStatus = ScanState.Ready,
            CreatedAt = DateTime.UtcNow
        };
        db.Videos.Add(video);
        await db.SaveChangesAsync();

        var config = new ConfigurationBuilder().Build();
        var videoService = new VideoService(db, config);

        var result = await videoService.GetVideoByIdAsync(video.Id, "testuser", "http://localhost:5000");

        Assert.NotNull(result);
        Assert.Equal(2, result.SubtitleTracks.Count);

        // Track 0 must be the clean manual subtitle (Default = true)
        var firstTrack = result.SubtitleTracks[0];
        Assert.Equal("en", firstTrack.Language);
        Assert.Equal("English", firstTrack.Label);
        Assert.True(firstTrack.IsDefault);

        // Track 1 is the auto-generated subtitle
        var secondTrack = result.SubtitleTracks[1];
        Assert.Equal("en-orig", secondTrack.Language);
        Assert.Equal("English (Auto-generated)", secondTrack.Label);
        Assert.False(secondTrack.IsDefault);
    }
}
